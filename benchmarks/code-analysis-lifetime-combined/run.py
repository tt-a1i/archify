#!/usr/bin/env python3
"""Replay recent concern-specific contracts after composing original histories.

Use the same fixed source checkouts as the individual benchmark READMEs. Historical
captures are actual prior producer outputs, not captures regenerated by this CLI.
"""
import argparse,json,subprocess,sys
from pathlib import Path
p=argparse.ArgumentParser()
for n in ['cli','samples-root','history-root','out']:p.add_argument('--'+n,type=Path,required=True)
a=p.parse_args()
for n in vars(a):setattr(a,n,getattr(a,n).resolve())
root=Path(__file__).resolve().parents[2];w=a.history_root;s=a.samples_root
assert not a.out.exists();a.out.mkdir(parents=True)
recipes=[
 ('rust-lifetime','code-analysis-rust-lifetime-inherent/run.py',['--sample',s/'regex']),
 ('rust-specialized','code-analysis-rust-specialized-inherent/run.py',['--samples-root',s,'--candidate-model','rust-source-direct-v4']),
 ('rust-pair','code-analysis-rust-lifetime-inherent/pair.py',['--work',a.out/'owned']),
 ('rust-history','code-analysis-rust-lifetime-inherent/extras.py',['--samples-root',s,'--v1',w/'combined-rust-source/regex','--v2',w/'rust-specialized-accepted-baseline/default','--v3',w/'rust-lifetime-baseline-replay/capture']),
 ('java-parent','code-analysis-java-captured-superclass/run.py',['--sample',s/'commons-lang','--candidate-model','java-static-lexical-v5']),
 ('java-project','code-analysis-java-project-deps/run.py',['--sample',s/'slf4j']),
 ('java-pair','code-analysis-java-project-deps/pair.py',['--base-root',w/'java-project-deps-upstream/slf4j-99e356974859a4cac2f5e533de2d8232d9d5dbe6','--head-root',w/'java-project-deps-upstream/slf4j-1c13755b2520e511bc41b5c6fdc8bd6c58e529c0']),
 ('java-history','code-analysis-java-project-deps/freshness.py',['--capture',a.out/'java-project/capture','--baseline',w/'java-project-deps-baseline-replay/capture','--sample',s/'slf4j']),
 ('ts-forward','code-analysis-forwarded-exports/run.py',['--sample',s/'redux']),
 ('ts-pair','code-analysis-forwarded-exports/real-change.py',['--samples-root',s]),
]
commands=[]
for name,script,args in recipes:
 cmd=[sys.executable,str(root/'benchmarks'/script),'--cli',str(a.cli),'--out',str(a.out/name),*map(str,args)]
 r=subprocess.run(cmd,capture_output=True,text=True,cwd=root)
 for suffix,value in [('stdout',r.stdout),('stderr',r.stderr)]:(a.out/(name+'.'+suffix)).write_text(value)
 commands.append(dict(name=name,command=cmd,exit=r.returncode));(a.out/'commands.json').write_text(json.dumps(commands,indent=2)+'\n')
 print(name,'exit',r.returncode,flush=True)
 if r.returncode:print(r.stderr[-2000:],flush=True)
sys.exit(any(c['exit']for c in commands))
