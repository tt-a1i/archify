// Bundles the parser and schema packages into vendor/ so a copied Skill runs
// Code Analysis without installing node_modules. Bundles stay unminified so
// people and agents can still read them; only unused package files are dropped.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = fileURLToPath(new URL('../', import.meta.url));
const vendor = path.join(root, 'vendor');
const bundles = {
  'typescript.cjs': "module.exports = require('typescript');",
  'deps.cjs': [
    "export { lexAndParse } from 'java-parser';",
    "export { DOMParser } from '@xmldom/xmldom';",
    "export { default as Ajv2020 } from 'ajv/dist/2020.js';",
    "export { default as AjvDraft04 } from 'ajv-draft-04';",
    "export { default as addFormats } from 'ajv-formats';",
  ].join('\n'),
};

const outputs = new Map();
const packages = new Map();
for (const [name, contents] of Object.entries(bundles)) {
  const result = await build({
    stdin: { contents, resolveDir: root, loader: 'js', sourcefile: `vendor/${name}` },
    absWorkingDir: root, bundle: true, platform: 'node', target: 'node18', format: 'cjs', write: false,
    charset: 'utf8', legalComments: 'inline', metafile: true,
    banner: { js: `/*! Generated by scripts/build-vendor.mjs; see vendor/LICENSES.txt. Do not edit. */` },
  });
  // Module paths in esbuild comments and wrapper keys must not depend on where or how packages were installed.
  const code = result.outputFiles[0].text.replace(/^(\/\/ |  ")(?:\.\.\/)*node_modules\/(?:\.pnpm\/[^/]+\/node_modules\/)?/gm, '$1node_modules/');
  outputs.set(name, Buffer.from(code));
  for (const input of Object.keys(result.metafile.inputs)) {
    // pnpm nests packages under node_modules/.pnpm/<id>/node_modules/<name>; the last segment names the package.
    const posix = input.split(path.sep).join('/');
    const at = posix.lastIndexOf('node_modules/');
    if (at === -1) continue;
    const name = /^(?:@[^/]+\/)?[^/]+/.exec(posix.slice(at + 'node_modules/'.length))[0];
    packages.set(name, path.join(root, posix.slice(0, at + 'node_modules/'.length + name.length)));
  }
}

const notices = ['Third-party packages bundled into vendor/*.cjs by scripts/build-vendor.mjs.\n'];
for (const [name, dir] of [...packages].sort(([a], [b]) => (a < b ? -1 : 1))) {
  const manifest = JSON.parse(fs.readFileSync(path.join(dir, 'package.json'), 'utf8'));
  const entries = fs.readdirSync(dir);
  const licenseFile = entries.find(file => /^licen[cs]e(\.|$)/i.test(file));
  if (!licenseFile) throw new Error(`${name} has no license file to bundle`);
  const extraNotices = entries.filter(file => /^(?:notice|thirdpartynotice)/i.test(file)).sort();
  const sections = [licenseFile, ...extraNotices].map(file => {
    const body = fs.readFileSync(path.join(dir, file), 'utf8').replace(/\r\n/g, '\n').replace(/[ \t]+$/gm, '').trim();
    return file === licenseFile ? body : `--- ${file} ---\n\n${body}`;
  });
  notices.push(`${'='.repeat(78)}\n${name}@${manifest.version} (${manifest.license})\n${'='.repeat(78)}\n\n${sections.join('\n\n')}\n`);
}
outputs.set('LICENSES.txt', Buffer.from(notices.join('\n')));

if (process.argv.includes('--check')) {
  for (const [name, bytes] of outputs) {
    const file = path.join(vendor, name);
    if (!fs.existsSync(file) || !fs.readFileSync(file).equals(bytes)) {
      throw new Error(`vendor/${name} is stale; run pnpm run build:vendor`);
    }
  }
} else {
  fs.mkdirSync(vendor, { recursive: true });
  for (const [name, bytes] of outputs) fs.writeFileSync(path.join(vendor, name), bytes);
}
