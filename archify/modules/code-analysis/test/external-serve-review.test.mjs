import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { request } from 'node:http';
import { test } from 'node:test';
import { startAnalysisView } from '../bin/serve.mjs';
import { reviewTargetDigest } from '../lib/review.mjs';

test('serve review: token, explicit reason, current evidence, task review and revocation share one baseline', async (t) => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'archify-external-review-http-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  fs.writeFileSync(path.join(root, 'main.mjs'), 'export const value = 1;\n');
  fs.writeFileSync(path.join(root, 'eslint.json'), JSON.stringify([{ filePath: 'main.mjs', messages: [{ ruleId: 'example-rule', severity: 1, message: 'Review this declaration', line: 1, column: 14, endLine: 1, endColumn: 19 }] }]));
  const config = path.join(root, 'config.json');
  fs.writeFileSync(config, JSON.stringify({ external: { sources: [{ id: 'eslint-web', format: 'eslint', file: 'eslint.json' }] } }));
  const ir = path.join(root, 'architecture.json');
  fs.writeFileSync(ir, JSON.stringify({ schema_version: 1, diagram_type: 'architecture', meta: { title: 'Review fixture', output: 'architecture.html' }, components: [{ id: 'app', type: 'backend', label: 'App', pos: [40, 40], size: [170, 64] }], connections: [] }));
  const view = await startAnalysisView([root, '--language', 'ts', '--config', config, '--ir', ir, '--out', path.join(root, 'view')]);
  t.after(() => new Promise((resolve) => { view.server.close(resolve); view.server.closeAllConnections(); }));
  const headers = { Origin: view.url, 'X-Analysis-Token': view.token, 'Content-Type': 'application/json' };
  const review = async (body, authorized = true) => fetch(`${view.url}/review`, { method: 'POST', headers: authorized ? headers : {}, body: JSON.stringify(body) });
  const id = 'CONV-012345abcdef';
  assert.equal((await review({ action: 'accept', id, reason: 'intentional' }, false)).status, 403);
  assert.equal((await review({ action: 'accept', id, expected: '0'.repeat(64), reason: 'intentional' })).status, 409);
  const analyzed = await fetch(`${view.url}/analyze`, { method: 'POST', headers });
  const initialHtml = await analyzed.text();
  assert.equal(analyzed.status, 200, initialHtml);
  const payloadOf = (html) => JSON.parse(html.match(/id="bauify-analysis">([\s\S]*?)<\/script>/)[1]);
  const initialPayload = payloadOf(initialHtml);
  const findings = JSON.parse(fs.readFileSync(path.join(root, 'view/analysis/findings.json'), 'utf8'));
  const diagnostic = findings.diagnostics.find((d) => d.external);
  assert.ok(diagnostic);
  const expected = reviewTargetDigest(diagnostic);
  assert.equal((await review({ action: 'accept', id: diagnostic.id, reason: 'intentional' })).status, 400, 'acceptance must identify the exact claim displayed by the page');
  assert.equal((await review({ action: 'accept', id: diagnostic.id, expected, reason: '  ' })).status, 422);
  assert.equal(fs.existsSync(view.baseline), false, 'invalid decisions never create a baseline');
  const contextFile = path.join(root, 'view/analysis/view-context.json');
  const contextBytes = fs.readFileSync(contextFile, 'utf8');
  fs.rmSync(contextFile);
  assert.equal((await review({ action: 'accept', id: diagnostic.id, expected, reason: 'prepare the new view first' })).status, 422);
  assert.equal(fs.existsSync(view.baseline), false, 'a view preparation failure must not persist a review decision');
  fs.writeFileSync(contextFile, contextBytes);
  const configBytes = fs.readFileSync(config, 'utf8');
  const reportBytes = fs.readFileSync(path.join(root, 'eslint.json'), 'utf8');
  const factsBytes = fs.readFileSync(path.join(root, 'view/analysis/raw-facts.json'), 'utf8');
  fs.rmSync(config);
  fs.rmSync(path.join(root, 'eslint.json'));
  // HTTP chunks may divide one UTF-8 character. The recorded review reason must
  // keep the user's original text rather than silently replacing its bytes.
  const reason = '按接口契约保留此声明。';
  const payload = Buffer.from(JSON.stringify({ action: 'accept', id: diagnostic.id, expected, reason }));
  const split = payload.indexOf(Buffer.from('按')) + 1;
  const saved = await new Promise((resolve, reject) => {
    const req = request(`${view.url}/review`, { method: 'POST', headers }, (res) => {
      let body = '';
      res.setEncoding('utf8');
      res.on('data', (chunk) => { body += chunk; });
      res.on('end', () => resolve({ status: res.statusCode, body: JSON.parse(body) }));
    });
    req.on('error', reject);
    req.write(payload.subarray(0, split));
    setImmediate(() => req.end(payload.subarray(split)));
  });
  assert.equal(saved.status, 200, JSON.stringify(saved.body));
  assert.equal(saved.body.review.findings[diagnostic.id].status, 'accepted');
  assert.equal(saved.body.refreshRequired, false);
  assert.equal(saved.body.artifactsSaved, true);
  const acceptedPayload = payloadOf(saved.body.html);
  assert.equal(acceptedPayload.findings.find((f) => f.id === diagnostic.id).review.status, 'accepted');
  assert.equal(acceptedPayload.overview.counts.accepted, 1);
  assert.deepEqual(acceptedPayload.overview.coverage, initialPayload.overview.coverage, 'reviewing retains the captured scan scope even when config and reports disappeared');
  assert.equal(fs.readFileSync(path.join(root, 'view/analysis/raw-facts.json'), 'utf8'), factsBytes);
  assert.equal(fs.readFileSync(path.join(root, 'view/analysis/repo.analysis.html'), 'utf8'), saved.body.html);
  assert.equal(fs.existsSync(path.join(root, 'view/analysis.previous')), false, 'a review is not a new analysis run');
  const cached = await fetch(`${view.url}/analyze`, { method: 'POST', headers });
  assert.equal(cached.status, 200);
  assert.equal(await cached.text(), saved.body.html, 'reload uses the reviewed snapshot without importing unavailable reports');
  assert.equal(JSON.parse(fs.readFileSync(view.baseline, 'utf8')).accepted[0].reason, reason);
  const bytes = fs.readFileSync(view.baseline, 'utf8');
  fs.writeFileSync(config, configBytes);
  fs.writeFileSync(path.join(root, 'eslint.json'), '{broken');
  const failedRefresh = await fetch(`${view.url}/analyze`, { method: 'POST', headers: { ...headers, 'X-Analysis-Refresh': '1' } });
  assert.equal(failedRefresh.status, 500, 'only explicit re-analysis reloads external reports');
  assert.equal((await failedRefresh.json()).diagnostics[0].code, 'external/input-not-json');
  assert.equal(fs.readFileSync(view.baseline, 'utf8'), bytes, 'a failed view refresh does not roll back a saved review');
  const recoveredCache = await fetch(`${view.url}/analyze`, { method: 'POST', headers });
  assert.equal(recoveredCache.status, 200);
  assert.equal(await recoveredCache.text(), saved.body.html, 'a failed re-analysis preserves the prior successful HTML cache as well as its disk files');
  fs.writeFileSync(path.join(root, 'eslint.json'), reportBytes);
  const task = await fetch(`${view.url}/task`, { method: 'POST', headers, body: JSON.stringify({ ids: [diagnostic.id] }) });
  assert.equal(task.status, 200);
  assert.equal((await task.json()).task.findings[0].review.reason, reason);
  const tooLarge = await fetch(`${view.url}/task`, { method: 'POST', headers, body: JSON.stringify({ ids: [diagnostic.id], padding: '字'.repeat(6000) }) });
  assert.equal(tooLarge.status, 413, 'the request limit counts bytes rather than UTF-16 characters');

  const report = JSON.parse(fs.readFileSync(path.join(root, 'eslint.json'), 'utf8'));
  report[0].messages[0].message = 'A revised claim about the same stable source location';
  fs.writeFileSync(path.join(root, 'eslint.json'), JSON.stringify(report));
  const refreshed = await fetch(`${view.url}/analyze`, { method: 'POST', headers: { ...headers, 'X-Analysis-Refresh': '1' } });
  assert.equal(refreshed.status, 200, await refreshed.text());
  const current = JSON.parse(fs.readFileSync(path.join(root, 'view/analysis/findings.json'), 'utf8')).diagnostics.find((d) => d.external);
  assert.equal(current.id, diagnostic.id);
  assert.notEqual(reviewTargetDigest(current), expected);
  const taskFor = (expected) => fetch(`${view.url}/task`, { method: 'POST', headers, body: JSON.stringify({ ids: [current.id], expected }) });
  const staleTask = await taskFor({ [current.id]: expected });
  assert.equal(staleTask.status, 409, 'a stable source snapshot must not export a different report claim from an old page');
  assert.equal((await staleTask.json()).diagnostics[0].code, 'task/finding-changed');
  for (const invalid of [null, 'invalid', {}, { [current.id]: null }, { [current.id]: 'invalid' }, []]) assert.equal((await taskFor(invalid)).status, 400, 'a supplied claim map must not silently fall back to ids-only behavior');
  const currentTask = await taskFor({ [current.id]: reviewTargetDigest(current) });
  assert.equal(currentTask.status, 200);
  assert.equal((await currentTask.json()).task.facts[0].statement, current.message);
  assert.equal((await review({ action: 'accept', id: diagnostic.id, expected, reason: 'from an old page' })).status, 409);
  assert.equal(fs.readFileSync(view.baseline, 'utf8'), bytes, 'a stale page cannot accept a new claim with the same finding id');
  fs.appendFileSync(path.join(root, 'main.mjs'), 'export const later = value;\n');
  assert.equal((await review({ action: 'accept', id: current.id, expected: reviewTargetDigest(current), reason: 'stale source' })).status, 409);
  assert.equal(fs.readFileSync(view.baseline, 'utf8'), bytes, 'changed evidence cannot overwrite the prior decision');
  const overviewFile = path.join(root, 'view/analysis/overview.json');
  fs.rmSync(overviewFile);
  fs.mkdirSync(overviewFile);
  const revoked = await review({ action: 'revoke', id: diagnostic.id });
  assert.equal(revoked.status, 200);
  const updated = await revoked.json();
  assert.equal(updated.saved, true);
  assert.equal(updated.artifactsSaved, false);
  assert.equal(updated.warnings[0].code, 'review/artifacts-not-updated');
  assert.equal(payloadOf(updated.html).findings.find((f) => f.id === diagnostic.id).review.status, 'open');
  assert.equal(await (await fetch(`${view.url}/analyze`, { method: 'POST', headers })).text(), updated.html, 'an artifact write failure still leaves an authoritative in-memory view');
  assert.deepEqual(JSON.parse(fs.readFileSync(view.baseline, 'utf8')).accepted, []);
  assert.equal(fs.readdirSync(path.join(root, 'view/analysis')).some((name) => name.includes('.next-')), false, 'failed artifact publication removes its temporary files');
});
