#!/usr/bin/env node
// Fetch the pinned full-colour logos listed in brand-marks/logos.json,
// sanitize them, and write renderers/shared/generated-brand-logos.mjs.
//
//   node scripts/generate-brand-logos.mjs [--cache <dir>]
//
// Upstream bytes are fetched at the pinned commit of each provider; their
// sha256 is recorded with the license so every embedded logo is traceable.
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { logoBodyProblems, sanitizeLogoSvg } from './brand-logo-sanitize.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const manifest = JSON.parse(fs.readFileSync(path.join(root, 'brand-marks', 'logos.json'), 'utf8'));
const catalog = JSON.parse(fs.readFileSync(path.join(root, 'brand-marks', 'catalog.json'), 'utf8'));
const outputPath = path.join(root, 'renderers', 'shared', 'generated-brand-logos.mjs');
const cacheFlag = process.argv.indexOf('--cache');
const cacheDir = cacheFlag > 0 ? process.argv[cacheFlag + 1] : null;
const known = new Set(catalog.marks.map((m) => m.id));

function rawUrl(provider, file) {
  const repo = new URL(provider.repository).pathname.replace(/^\//, '');
  return `https://raw.githubusercontent.com/${repo}/${provider.commit}/${file}`;
}

async function upstream(provider, file) {
  const url = rawUrl(provider, file);
  const cached = cacheDir && path.join(cacheDir, provider.commit, file);
  if (cached && fs.existsSync(cached)) return { url, bytes: fs.readFileSync(cached) };
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
  const bytes = Buffer.from(await response.arrayBuffer());
  if (cached) { fs.mkdirSync(path.dirname(cached), { recursive: true }); fs.writeFileSync(cached, bytes); }
  return { url, bytes };
}

function luminance(hex) {
  const v = hex.length === 3 ? [...hex].map((c) => c + c).join('') : hex;
  const ch = (o) => { const c = Number.parseInt(v.slice(o, o + 2), 16) / 255; return c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4; };
  return 0.2126 * ch(0) + 0.7152 * ch(2) + 0.0722 * ch(4);
}
function nearWhiteOnly(body) {
  const colours = [...body.matchAll(/(?:fill|stroke|stop-color)[=:]"?\s*(#[0-9a-f]{3,6}\b|white|black|none|currentColor)/gi)].map((m) => m[1].toLowerCase())
    .filter((c) => c !== 'none');
  const painted = /<(path|circle|rect|ellipse|polygon|polyline|line)\b(?![^>]*fill=)/.test(body) && !/<g fill=/.test(body);
  if (!colours.length || painted) return false;
  return colours.every((c) => c === 'white' || (c.startsWith('#') && [3, 6].includes(c.length - 1) && luminance(c.slice(1)) >= 0.7));
}

const out = [];
for (const entry of manifest.logos) {
  if (!known.has(entry.id)) throw new Error(`${entry.id} is not a brand-marks/catalog.json id`);
  const provider = manifest.providers[entry.provider];
  if (!provider) throw new Error(`${entry.id}: unknown provider ${entry.provider}`);
  const { url, bytes } = await upstream(provider, entry.file);
  const { viewBox, body } = sanitizeLogoSvg(bytes.toString('utf8'), `al-${entry.id}`);
  const problems = logoBodyProblems(body);
  if (problems.length) throw new Error(`${entry.id}: ${problems.join(', ')}`);
  out.push({
    id: entry.id,
    viewBox,
    body,
    // Logos drawn only in white or near-white need the ink plate to stay visible.
    inkPlate: nearWhiteOnly(body),
    provenance: {
      provider: provider.name,
      license: provider.license,
      repository: provider.repository,
      commit: provider.commit,
      file: entry.file,
      url,
      sha256: createHash('sha256').update(bytes).digest('hex'),
    },
  });
}
out.sort((a, b) => a.id.localeCompare(b.id));
const banner = '// Generated by scripts/generate-brand-logos.mjs from brand-marks/logos.json.\n// Sanitized full-colour logos; see NOTICE and third_party/. Do not edit by hand.\n';
fs.writeFileSync(outputPath, `${banner}export const BRAND_LOGOS = Object.freeze(${JSON.stringify(out, null, 1)});\n`);
console.log(`generated ${path.relative(root, outputPath)} (${out.length} logos)`);
