// One base (English) catalog defines every renderer-owned message key and
// its interpolation placeholders. Built-in catalogs (currently zh-CN and es)
// ship as complete, code-reviewed translations of that base. Any other
// locale — including Korean — is supplied by the caller as translation DATA
// through registerLocale(), validated against the same base, and rendered
// through the same escaping/formatting path below. This keeps adding a
// language an additive data change instead of a renderer code change.
//
// examples/locales/ko.json carries the Korean translations that used to be
// hard-coded here as a worked example of that data contract; examples/locales/
// fr.partial.json demonstrates the same contract with a second, previously
// unsupported language and intentionally partial coverage (missing keys fall
// back to English; see registerLocale()/validateTranslations()).
export const SUPPORTED_LOCALES = ['en', 'zh-CN', 'es'];
export const DEFAULT_LOCALE = 'en';

const ESCAPE_MAP = { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' };

export function escapeHtml(value) {
  return String(value ?? '').replace(/[&<>"']/g, (character) => ESCAPE_MAP[character]);
}

