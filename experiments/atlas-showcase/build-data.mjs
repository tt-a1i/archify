#!/usr/bin/env node
// Builds data.js for the Atlas showcase demos from a real code-analysis run.
//
//   node archify/bin/archify.mjs code-analysis check <repo> --out <out-dir> [--config c.json]
//   node experiments/atlas-showcase/build-data.mjs <out-dir> [repo-name]
//
// The payload is the Atlas payload (overlay/atlas.mjs buildAtlas), unchanged,
// plus the few fields the demos read for side panels: finding messages,
// locations, boundary imports, thresholds, module-level edges and the summary.
// Nothing here is new analysis.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildAtlas } from '../../archify/modules/code-analysis/overlay/atlas.mjs';

const [outDir, repoName] = process.argv.slice(2);
if (!outDir) {
  console.error('usage: build-data.mjs <analysis-out-dir> [repo-name]');
  process.exit(2);
}
const read = (name) => JSON.parse(readFileSync(path.join(outDir, name), 'utf8'));
const graph = read('module-graph.json');
const facts = read('raw-facts.json');
const findings = read('findings.json');
let review = null;
try { review = read('review.json'); } catch { review = null; }

const atlas = buildAtlas({ graph, facts, findings: findings.diagnostics, review });
if (!atlas) throw new Error('buildAtlas returned null: raw facts or module graph missing');

const byId = new Map(findings.diagnostics.map((f) => [f.id, f]));
for (const entry of atlas.findings) {
  const f = byId.get(entry.id);
  const s = f.subject || {};
  entry.message = f.message;
  entry.fix = (f.supportedFixes || [])[0] || null;
  entry.file = s.file ?? f.evidence?.imports?.[0]?.file ?? null;
  entry.line = s.line ?? f.evidence?.imports?.[0]?.line ?? null;
  if (f.code === 'complexity/function') {
    entry.complexity = f.evidence?.complexity ?? null;
    entry.nesting = f.evidence?.nesting ?? null;
    entry.length = f.evidence?.length ?? null;
  }
  if (f.code === 'architecture/boundary') {
    entry.imports = (f.evidence?.imports || []).map((i) => ({ file: i.file, line: i.line, to: i.to }));
  }
}

const moduleIndex = new Map(atlas.modules.map((m, i) => [m.id, i]));
atlas.moduleEdges = (graph.edges || [])
  .filter((e) => moduleIndex.has(e.from) && moduleIndex.has(e.to))
  .map((e) => [moduleIndex.get(e.from), moduleIndex.get(e.to), e.weight]);
atlas.summary = findings.summary;
atlas.thresholds = findings.diagnostics.find((f) => f.code === 'complexity/function')?.evidence?.thresholds ?? null;
atlas.repository = {
  name: repoName || findings.repository?.root || 'repository',
  revision: findings.repository?.revision ?? findings.repository?.baseRevision ?? null,
  sourceKind: findings.repository?.sourceKind ?? null,
  adapter: findings.repository?.adapter ?? null,
};

const here = path.dirname(fileURLToPath(import.meta.url));
const target = path.join(here, 'data.js');
writeFileSync(target, `// Generated by build-data.mjs from a real code-analysis run. Do not edit by hand.\nwindow.ATLAS_DATA = ${JSON.stringify(atlas)};\n`);
console.log(`wrote ${path.relative(process.cwd(), target)}: ${atlas.modules.length} modules, ${atlas.files.length} files, ${atlas.edges.length} file edges, ${atlas.functions.length} functions, ${atlas.findings.length} findings`);
