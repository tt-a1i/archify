#!/usr/bin/env node
// Builds data.js for the 3D Atlas proof of concept from a real code-analysis run.
//
//   node archify/bin/archify.mjs code-analysis check <repo> --out <run-dir> [--config c.json]
//   node experiments/atlas-3d/build-data.mjs <run-dir> <dataset-id> [display name]
//
// Writes data-<dataset-id>.js, which registers the dataset in
// window.ATLAS_DATASETS; index.html lists every dataset it loads and shows
// the one named in the URL hash (#archify, #langchain-core, ...).
//
// The scene draws exactly the Atlas payload: buildAtlas() from
// overlay/atlas.mjs, called on the run's raw facts, module graph, findings and
// review, unchanged. The only addition is each finding's own message and first
// suggested fix, copied verbatim from findings.json for the side panel. Nothing
// is measured or scored here; the checks below stop the build if the payload
// and the run disagree.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildAtlas } from '../../archify/modules/code-analysis/overlay/atlas.mjs';

const [runDir, datasetId, displayName] = process.argv.slice(2);
if (!runDir || !datasetId || !/^[a-z0-9-]+$/.test(datasetId)) { console.error('usage: build-data.mjs <analysis-run-dir> <dataset-id: a-z 0-9 -> [display name]'); process.exit(2); }
const read = (name) => JSON.parse(readFileSync(path.join(runDir, name), 'utf8'));
const graph = read('module-graph.json');
const facts = read('raw-facts.json');
const findings = read('findings.json');
let review = null;
try { review = read('review.json'); } catch { review = null; }

const atlas = buildAtlas({ graph, facts, findings: findings.diagnostics, review });
if (!atlas) throw new Error('buildAtlas returned null: the run has no raw facts');

// ---- consistency with the run: the same checks the Atlas tests make ----
const fail = (what) => { throw new Error(`3D data disagrees with the run: ${what}`); };
const owned = new Set(Object.keys(graph.fileModules || {}));
if (atlas.files.length !== owned.size || atlas.files.some(([p]) => !owned.has(p))) fail('files are not exactly the module graph\'s files');
const paths = atlas.files.map(([p]) => p);
const expectedEdges = new Set(facts.imports.filter((i) => i.resolved && i.from !== i.to && owned.has(i.from) && owned.has(i.to)).map((i) => `${i.from}>${i.to}`));
const drawnEdges = new Set(atlas.edges.map(([a, b]) => `${paths[a]}>${paths[b]}`));
if (drawnEdges.size !== atlas.edges.length || drawnEdges.size !== expectedEdges.size || [...expectedEdges].some((e) => !drawnEdges.has(e))) fail('file dependencies differ from resolved in-tree imports');
if (atlas.functions.length !== (facts.functions || []).filter((fn) => owned.has(fn.file)).length) fail('function count differs from raw facts');
const ids = new Set(atlas.findings.map((f) => f.id));
if (ids.size !== findings.diagnostics.length || findings.diagnostics.some((d) => !ids.has(d.id))) fail('findings are not exactly the run\'s findings');
for (const fn of atlas.functions) if (fn[6] !== -1 && atlas.findings[fn[6]].fn === undefined) fail(`function ${fn[1]} points at a finding that does not point back`);

// ---- verbatim text for the side panel ----
const byId = new Map(findings.diagnostics.map((d) => [d.id, d]));
atlas.detail = Object.fromEntries(atlas.findings.map((f) => {
  const d = byId.get(f.id);
  return [f.id, { message: d.message, fix: (d.supportedFixes || [])[0] || null, file: d.subject?.file ?? null, line: d.subject?.line ?? null }];
}));
atlas.run = {
  repository: displayName || datasetId,
  revision: findings.repository?.revision ?? findings.repository?.baseRevision ?? null,
  sourceKind: findings.repository?.sourceKind ?? null,
  adapter: findings.repository?.adapter ?? null,
  rules: findings.rules,
  summary: findings.summary,
};

const here = path.dirname(fileURLToPath(import.meta.url));
const target = path.join(here, `data-${datasetId}.js`);
writeFileSync(target, `// Generated by build-data.mjs: the Atlas payload (overlay/atlas.mjs buildAtlas) of one run. Do not edit by hand.\n(window.ATLAS_DATASETS = window.ATLAS_DATASETS || {})[${JSON.stringify(datasetId)}] = ${JSON.stringify(atlas)};\n`);
console.log(`wrote ${path.relative(process.cwd(), target)}: ${atlas.modules.length} modules, ${atlas.files.length} files, ${atlas.edges.length} file dependencies, ${atlas.functions.length} functions, ${atlas.findings.length} findings (checked against the run)`);
